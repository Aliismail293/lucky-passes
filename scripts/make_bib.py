"""Build paper/references.bib from the fetched, verified metadata only (ground rule B2.3).

Keys and links come from the table in paper/citations_verified.md; title, authors, year and venue come from
paper/verified_pages.json (what the arXiv / Crossref / ACL Anthology page said when it was fetched). Nothing is
typed by hand, so a reference can't drift from what was verified. arXiv entries are cited as arXiv preprints; if a
paper is later cited in its venue version, that version must be verified first (see citations_verified.md, Notes).

Usage: uv run python scripts/make_bib.py
"""

import json
import re
import sys
from pathlib import Path

PAPER = Path(__file__).resolve().parent.parent / "paper"
ROW = re.compile(r"^\| \d+ \| (\w+) \| .*? \| (https://\S+)")


def keys_by_url(table: str) -> dict[str, str]:
    keys = {}
    for line in table.splitlines():
        match = ROW.match(line)
        if match:
            keys[match.group(2)] = match.group(1)
    return keys


def bib_author(name: str) -> str:
    """'Liu, Jiayi' stays as is; 'Tom Kwiatkowski' becomes 'Kwiatkowski, Tom'."""
    if "," in name:
        return name
    parts = name.split()
    return f"{parts[-1]}, {' '.join(parts[:-1])}" if len(parts) > 1 else name


def escape(text: str) -> str:
    return text.replace("&", r"\&").replace("%", r"\%").replace("®", "").replace("#", r"\#")


def entry(key: str, page: dict) -> str:
    year = re.match(r"\d{4}", page["date"]).group(0)
    authors = " and ".join(bib_author(a) for a in page["authors"])
    fields = {"title": "{" + escape(page["title"]) + "}", "author": authors, "year": year}
    url = page["url"]
    if "arxiv.org/abs/" in url:
        arxiv_id = url.rsplit("/", 1)[1]
        kind = "misc"
        fields.update({"howpublished": f"arXiv:{arxiv_id}", "eprint": arxiv_id, "archivePrefix": "arXiv", "url": url})
    else:
        venue = escape(page.get("venue", ""))
        kind = "inproceedings" if "Proceedings" in venue else "article"
        fields["booktitle" if kind == "inproceedings" else "journal"] = venue
        doi = url.split("doi.org/", 1)[1] if "doi.org/" in url else None
        if doi:
            fields["doi"] = doi
        fields["url"] = url
    body = ",\n".join(f"  {name} = {{{value}}}" for name, value in fields.items())
    return f"@{kind}{{{key},\n{body}\n}}\n"


def main() -> int:
    pages = {p["url"]: p for p in json.loads((PAPER / "verified_pages.json").read_text())}
    keys = keys_by_url((PAPER / "citations_verified.md").read_text())
    entries, missing = [], []
    for url, key in keys.items():
        if url not in pages or pages[url]["status"] != 200:
            missing.append(key)
            continue
        entries.append(entry(key, pages[url]))
    if missing:
        print("not verified, left out:", ", ".join(missing), file=sys.stderr)
        return 1
    header = "% Generated by scripts/make_bib.py from paper/verified_pages.json. Do not edit by hand.\n\n"
    (PAPER / "references.bib").write_text(header + "\n".join(entries))
    print(f"wrote {len(entries)} entries to paper/references.bib")
    return 0


if __name__ == "__main__":
    sys.exit(main())
